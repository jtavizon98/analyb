r"""LaTeX generation from registered plot/table entries.

Scripts call register() per plot and register_table() per table; write_tex()
emits a standalone compilable .tex with a guarded preamble
(\ifdefined\analybmain).  write_master() emits the combined plots.tex that
defines \analybmain and \input{}s per-script documents.
"""

import logging
import os
import contextvars

logger = logging.getLogger(__name__)

# {script_id: [(section, filename, caption, width, label, __type__)]}
_registry_var = contextvars.ContextVar("analyb_latex_registry", default=None)


def _get_registry():
    reg = _registry_var.get()
    if reg is None:
        reg = {}
    return reg


def register(script_id, section, filename, caption=None, width=0.45, label=None):
    """Register a plot entry for the LaTeX output."""
    reg = dict(_get_registry())
    reg.setdefault(script_id, []).append({
        "__type__": "figure",
        "section": section,
        "filename": filename,
        "caption": caption,
        "width": width,
        "label": label,
    })
    _registry_var.set(reg)


def register_table(script_id, section, filename, caption=None, label=None):
    """Register a table entry for the LaTeX output.

    The table file (e.g. a ``.tex`` fragment generated by
    :meth:`YieldTable.to_latex`) will be included via ``\\input`` inside a
    ``table[H]`` float with ``\\centering``.
    """
    reg = dict(_get_registry())
    reg.setdefault(script_id, []).append({
        "__type__": "table",
        "section": section,
        "filename": filename,
        "caption": caption,
        "label": label,
    })
    _registry_var.set(reg)


def register_input(
    script_id, section, filename, *, page_break_before=False, page_break_after=False,
):
    """Register a non-floating LaTeX fragment included with ``\\input``.

    Use this for content such as a ``longtable`` or a formula reference which
    must appear inline, rather than inside a figure or table float.
    """
    reg = dict(_get_registry())
    entry = {
        "__type__": "input",
        "section": section,
        "filename": filename,
    }
    if page_break_before:
        entry["page_break_before"] = True
    if page_break_after:
        entry["page_break_after"] = True
    reg.setdefault(script_id, []).append(entry)
    _registry_var.set(reg)


def _escape_tex(s):
    """Escape plain text while preserving intentional ``$...$`` physics LaTeX."""
    replacements = {
        "\\": r"\textbackslash{}",
        "{": r"\{",
        "}": r"\}",
        "_": r"\_",
        "&": r"\&",
        "%": r"\%",
        "#": r"\#",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    parts = s.split("$")
    for index in range(0, len(parts), 2):
        parts[index] = "".join(replacements.get(char, char) for char in parts[index])
    return "$".join(parts)


def _build_sections(entries, asset_dir=None):
    r"""Group entries by section; emit figures, tables, and inline inputs.

    Figures retain their two-per-row layout and tables retain their solo
    floats.  Input fragments are emitted directly below the subsection, with
    no float wrapper, so they may contain environments such as ``longtable``.
    """
    sections = {}
    for e in entries:
        sections.setdefault(e["section"], []).append(e)

    tex = []
    for sec, items in sections.items():
        fig_items = [item for item in items if item.get("__type__") == "figure"]
        tab_items = [item for item in items if item.get("__type__") == "table"]
        input_items = [item for item in items if item.get("__type__") == "input"]

        if any(item.get("page_break_before") for item in items):
            tex.append(r"\clearpage")
            tex.append("")
        tex.append(r"\subsection{" + _escape_tex(sec) + "}")
        tex.append("")

        # --- figures: two per row ---
        i = 0
        while i < len(fig_items):
            a = fig_items[i]
            b = fig_items[i + 1] if i + 1 < len(fig_items) else None
            tex.append(r"\begin{figure}[H]")
            tex.append(r"  \centering")
            w_a = a.get("width", 0.45)
            cap_a = a.get("caption") or a.get("filename", "")
            base_a = os.path.splitext(a["filename"])[0]
            lbl_a = a.get("label") or ("fig:" + base_a.replace("-", "_").replace(".", "_"))
            tex.append(
                r"  \includegraphics[width=" + f"{w_a}\\textwidth]"
                r"{" + a["filename"] + "}"
            )
            if b:
                w_b = b.get("width", 0.45)
                tex.append(r"  \hfill")
                tex.append(
                    r"  \includegraphics[width=" + f"{w_b}\\textwidth]"
                    r"{" + b["filename"] + "}"
                )
            tex.append(r"  \caption{" + _escape_tex(cap_a) + "}")
            if b:
                base_b = os.path.splitext(b["filename"])[0]
                lbl_b = b.get("label") or ("fig:" + base_b.replace("-", "_").replace(".", "_"))
                tex.append(r"  \label{" + lbl_b + "}")
            else:
                tex.append(r"  \label{" + lbl_a + "}")
            tex.append(r"\end{figure}")
            tex.append("")
            i += 2

        # --- tables: one per float, never paired with figures ---
        for tab in tab_items:
            tex.append(r"\begin{table}[H]")
            tex.append(r"  \centering")
            input_path = os.path.join(asset_dir, tab["filename"]) if asset_dir else tab["filename"]
            tex.append(r"  \input{" + input_path + "}")
            cap = tab.get("caption") or tab.get("filename", "")
            base = os.path.splitext(tab["filename"])[0]
            lbl = tab.get("label") or ("tab:" + base.replace("-", "_").replace(".", "_"))
            tex.append(r"  \caption{" + _escape_tex(cap) + "}")
            tex.append(r"  \label{" + lbl + "}")
            tex.append(r"\end{table}")
            tex.append("")

        # --- inline fragments: no float environment ---
        for entry in input_items:
            input_path = os.path.join(asset_dir, entry["filename"]) if asset_dir else entry["filename"]
            tex.append(r"\input{" + input_path + "}")
            tex.append("")
        if any(item.get("page_break_after") for item in items):
            tex.append(r"\clearpage")
            tex.append("")
    return "\n".join(tex)


# Shared preamble for both standalone and master documents.
PREAMBLE_LINES = [
    r"\documentclass[a4paper,11pt]{article}",
    r"\usepackage[utf8]{inputenc}",
    r"\usepackage{graphicx}",
    r"\usepackage{booktabs}",
    r"\usepackage{longtable}",
    r"\usepackage{geometry}",
    r"\geometry{margin=1.5cm}",
    r"\usepackage[hidelinks]{hyperref}",
    r"\usepackage{physics}",
    r"\usepackage{siunitx}",
    r"\sisetup{locale=US, separate-uncertainty=true}",
    r"\usepackage{float}",
    r"\usepackage{upgreek}",
]


def _standalone_header(script_id):
    r"""Preamble + \begin{document} wrapped in \ifdefined\analybmain guard."""
    title = script_id.replace("_", " ").title()
    lines = [
        r"\ifdefined\analybmain",
        r"\def\analybdocend{}",
        r"\else",
    ]
    lines.extend(PREAMBLE_LINES)
    lines.append(r"\graphicspath{{" + script_id + r"/}}")
    lines.append(r"\title{" + title + "}")
    lines.append(r"\date{\today}")
    lines.append(r"\begin{document}")
    lines.append(r"\maketitle")
    lines.append(r"\tableofcontents")
    lines.append(r"\newpage")
    lines.append(r"\def\analybdocend{\end{document}}")
    lines.append(r"\fi")
    return "\n".join(lines) + "\n"


def _standalone_footer():
    r"""End standalone documents without leaving an open conditional."""
    return r"\analybdocend" + "\n"


def write_tex(script_id, save_path=None):
    r"""Write {script_id}.tex — a standalone compilable document with guarded preamble.

    When \analybmain is defined (e.g. when \input-ed from the master document
    plots.tex), the preamble and \begin/\end{document} are skipped so that only
    the figure body is included inline.
    """
    reg = _get_registry()
    entries = reg.get(script_id, [])
    if not entries:
        logger.warning("No entries registered for %r", script_id)
        return None

    if save_path is None:
        from . import config
        save_path = config.get_save_path() or os.path.join(os.getcwd(), "plots")

    body = _build_sections(entries, asset_dir=script_id)
    content = (
        f"% Auto-generated by analyb makelatex for script {script_id}\n"
        + _standalone_header(script_id)
        + body
        + "\n"
        + _standalone_footer()
    )

    os.makedirs(save_path, exist_ok=True)
    parent = os.path.dirname(os.path.normpath(save_path))
    tex_path = os.path.join(parent, f"{script_id}.tex")
    with open(tex_path, "w", encoding="utf-8") as fp:
        fp.write(content)
    logger.info("Wrote %s (%d entries)", tex_path, len(entries))
    return tex_path


def write_master(script_ids, save_path=None, title="Plots"):
    r"""Write the master plots.tex that \input{}s per-script documents.

    Defines \analybmain (if not already defined) before \input-ing each script's
    .tex file, so the guarded preamble is skipped and only the figure body is
    included.

    Uses a hidden registry file (.plots_registry.json) in save_path to
    accumulate script IDs across runs.  Always regenerates the full document
    from scratch so that the master is self-consistent.
    """
    if save_path is None:
        from . import config
        save_path = config.get_save_path() or os.path.join(os.getcwd(), "plots")

    import json

    registry_path = os.path.join(save_path, ".plots_registry.json")
    all_ids = []

    if os.path.exists(registry_path):
        with open(registry_path) as f:
            meta = json.load(f)
        all_ids = meta.get("script_ids", [])
        title = meta.get("title", title)

    for sid in script_ids:
        if sid not in all_ids:
            all_ids.append(sid)

    with open(registry_path, "w") as f:
        json.dump({"script_ids": all_ids, "title": title}, f)

    master_dir = os.path.dirname(os.path.join(save_path, "plots.tex"))
    lines = list(PREAMBLE_LINES)
    lines.append("")
    gpaths = "".join(
        r"{" + os.path.relpath(os.path.join(save_path, sid), master_dir) + r"/}"
        for sid in all_ids
    )
    if gpaths:
        lines.append(r"\graphicspath{" + gpaths + "}")
    lines.append("")
    lines.append(r"\title{" + title + "}")
    lines.append(r"\date{\today}")
    lines.append("")
    lines.append(r"\begin{document}")
    lines.append(r"\maketitle")
    lines.append(r"\tableofcontents")
    lines.append(r"\newpage")
    lines.append("")
    lines.append(r"\def\analybmain{}")
    lines.append("")
    for sid in all_ids:
        sec_title = sid.replace("_", " ").title()
        lines.append(r"\section{" + sec_title + "}")
        tex_rel = os.path.relpath(
            os.path.join(save_path, f"{sid}.tex"),
            master_dir,
        )
        lines.append(r"\input{" + tex_rel + "}")
        lines.append(r"\newpage")
        lines.append("")
    lines.append(r"\end{document}")

    tex_path = os.path.join(save_path, "plots.tex")
    with open(tex_path, "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines) + "\n")
    logger.info("Wrote master %s with %s", tex_path, all_ids)
    return tex_path


PAGE_MAP_SCHEMA = "analyb.plotbook_page_map"
PAGE_MAP_SCHEMA_VERSION = 1


def write_compact_plotbook(path, sections, *, rows_per_page=2, section_rows=None, page_map=False):
    r"""Write a two-column book with two or three rows and identifying captions.

    ``sections`` maps plain-text section headings to ordered ``(PDF, caption)``
    pairs. Supply yield then shape for each observable. Paths must be relative
    to the TeX directory; figures retain their vector content and aspect ratio.
    ``section_rows`` optionally overrides ``rows_per_page`` by section heading.
    Figure height limits preserve caption and heading space for either layout.

    ``page_map=True`` also writes ``<stem>.pagemap.json`` beside the TeX file:
    the intended page of every slot, from the same loop that emits the
    ``\clearpage`` boundaries. The TeX output is identical either way.
    """
    import json
    from pathlib import Path
    path = Path(path)
    pages = []
    lines = [r"\documentclass[a4paper,10pt]{article}",
             r"\usepackage[margin=12mm]{geometry}", r"\usepackage{graphicx}",
             r"\usepackage[T1]{fontenc}", r"\usepackage{lmodern}",
             r"\setlength{\parindent}{0pt}", r"\begin{document}"]
    if rows_per_page not in (2, 3) or any(r not in (2, 3) for r in (section_rows or {}).values()):
        raise ValueError("rows_per_page must be two or three")
    first = True
    for heading, entries in sections.items():
        rows = (section_rows or {}).get(heading, rows_per_page)
        per_page = rows * 2
        height = "0.405" if rows == 2 else "0.27"
        for offset in range(0, len(entries), per_page):
            if not first:
                lines.append(r"\clearpage")
            first = False
            lines += [r"{\large\bfseries " + _escape_tex(heading) + r"}\par\medskip"]
            batch = entries[offset:offset+per_page]
            slots = []
            pages.append({"page": len(pages) + 1, "section": heading, "rows": rows, "slots": slots})
            for row_start in range(0, len(batch), 2):
                row = batch[row_start:row_start+2]
                if not row:
                    continue
                for index, (filename, caption) in enumerate(row):
                    slots.append({"figure": str(filename), "caption": caption,
                                  "row": row_start // 2 + 1, "column": index + 1})
                    if index:
                        lines.append(r"\hfill")
                    lines += [r"\begin{minipage}[t]{0.485\textwidth}\centering",
                              r"\includegraphics[width=\linewidth,height=" + height + r"\textheight,keepaspectratio]{\detokenize{" + str(filename) + "}}",
                              r"\par\smallskip{\small " + _escape_tex(caption) + r"}",
                              r"\end{minipage}"]
                lines.append(r"\par\bigskip")
    lines.append(r"\end{document}")
    path.write_text("\n".join(lines)+"\n", encoding="utf-8")
    if page_map:
        record = {"schema": PAGE_MAP_SCHEMA, "schema_version": PAGE_MAP_SCHEMA_VERSION,
                  "tex": path.name, "pdf": path.with_suffix(".pdf").name,
                  "page_count": len(pages), "pages": pages}
        path.with_suffix(".pagemap.json").write_text(
            json.dumps(record, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return str(path)
